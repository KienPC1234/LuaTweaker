package com.luatweaker.neoforge.content.registrar;

import com.luatweaker.api.content.IContentService;
import com.luatweaker.api.content.IDatapackService;
import com.luatweaker.api.content.IFluidBuilder;
import com.luatweaker.api.log.LogStage;
import com.luatweaker.common.util.CallbackFirewall;
import org.jetbrains.annotations.NotNull;

/**
 * Generates the NeoForge-specific fluid bucket item models.
 *
 * <p>Vanilla-style JSON cannot express a fluid container; buckets must use the
 * {@code neoforge:fluid_container} model loader, so this file lives in the
 * NeoForge module. Everything else about a fluid (textures, blockstates, block
 * models) is loader-agnostic and generated by
 * {@code com.luatweaker.common.content.ContentVirtualFiles}.
 */
public final class FluidBucketAssets {

    private static final String JSON_EXTENSION = ".json";
    private static final String BUCKET_SUFFIX = "_bucket";
    private static final String DEFAULT_NAMESPACE = "luatweaker";

    private FluidBucketAssets() {
    }

    /**
     * Writes one {@code neoforge:fluid_container} bucket model per registered
     * fluid (plus the legacy {@code <id-without-_fluid>_bucket} alias the old
     * engine emitted). Physical files on disk always win: nothing is written
     * when the key already exists in the datapack map.
     */
    public static void inject(@NotNull IDatapackService datapackService,
                              @NotNull IContentService contentService) {
        for (IFluidBuilder builder : contentService.getRegisteredFluids()) {
            CallbackFirewall.run(() -> injectBucketAssets(datapackService, builder), LogStage.SYSTEM,
                    () -> "[FluidBucketAssets] Failed bucket assets for '" + builder.getId() + "'");
        }
    }

    private static void injectBucketAssets(@NotNull IDatapackService datapackService,
                                           @NotNull IFluidBuilder builder) {
        String[] parts = parseId(builder.getId());
        String namespace = parts[0];
        String id = parts[1];
        String bucketId = id + BUCKET_SUFFIX;
        String altBucketId = id.replace("_fluid", "") + BUCKET_SUFFIX;

        String bucketJson = "{\n"
                + "  \"loader\": \"neoforge:fluid_container\",\n"
                + "  \"parent\": \"neoforge:item/bucket\",\n"
                + "  \"fluid\": \"" + namespace + ":" + id + "\"\n"
                + "}";
        String bucketKey = "assets/" + namespace + "/models/item/" + bucketId + JSON_EXTENSION;
        String altBucketKey = "assets/" + namespace + "/models/item/" + altBucketId + JSON_EXTENSION;
        datapackService.addData(bucketKey, bucketJson);
        datapackService.addData(altBucketKey, bucketJson);
    }

    private static String[] parseId(String id) {
        if (id != null && id.contains(":")) {
            return id.split(":", 2);
        }
        return new String[]{DEFAULT_NAMESPACE, id != null ? id : "unknown"};
    }
}
